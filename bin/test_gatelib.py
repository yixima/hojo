# -*- coding: utf-8 -*-
"""`bin/gatelib.py` の回帰テスト。**ネットワークを使わない。**

なぜ要るか
----------
2026-09-04 の事故（福島県の参加申込 9/1 を取り落とし、提案書の 9/4 を
「参加申込」と誤ラベルした）は、**検査スクリプトに1件もテストが無かったため、
壊れていることが分からなかった。**既知の正解をここに固定資産として持つ。

    python3 bin/test_gatelib.py
"""
import datetime
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
from gatelib import extract_gates, earliest_gate  # noqa: E402

D = datetime.date
T = datetime.time
ok = fail = 0


def check(name, got, want):
    global ok, fail
    if got == want:
        ok += 1
        print('  OK   %s' % name)
    else:
        fail += 1
        print('  NG   %s\n       得た値 %r\n       期待値 %r' % (name, got, want))


# ── 1. 福島県。**事故そのもの。表の各行が「日付 → ラベル」で並ぶ** ──────
FUKUSHIMA = '''８ 実施のスケジュール
令和８年８月１８日（火） プロポーザル方式募集要領の公表 公募の開始
令和８年８月２１日（金）１７時まで 質問書の提出期限
令和８年８月２４日（月）１７時まで 質問書への回答
令和８年９月 １日（火）正午まで 参加申込書の提出期限
令和８年９月 ４日（金）正午まで 企画提案書の提出期限
令和８年９月 ８日（火）（予定） 一次審査結果の通知
令和８年９月１１日（金）（予定） 二次審査会の実施
令和８年９月１４日（月）（予定） 二次審査結果の通知'''
g = extract_gates(FUKUSHIMA)
kinds = {d: k for k, d, t, s in g}
check('福島 9/1 は参加申込', kinds.get(D(2026, 9, 1)), '参加申込')
check('福島 9/4 は提案書', kinds.get(D(2026, 9, 4)), '提案書')
check('福島 9/8 は関門でない', kinds.get(D(2026, 9, 8)), '不明')
check('福島 最早の関門', earliest_gate(g), ('参加申込', D(2026, 9, 1), T(12, 0)))
check('福島 8/21 は質問書＝関門でない', kinds.get(D(2026, 8, 21)), '不明')

# ── 2. おまつり歳時記。参加意向申出が先に来る ──────────────────
OMATSURI = '''参加意向申出書の提出期限 令和8年9月7日（月）17時必着
企画提案書の提出期限 令和8年9月29日（火）17時必着'''
g = extract_gates(OMATSURI)
check('おまつり 最早の関門', earliest_gate(g), ('参加申込', D(2026, 9, 7), T(17, 0)))

# ── 3. 前置き型。ラベルが日付の前にある ───────────────────────
MAE = '参加表明書の締切：2026-09-10　　企画提案書の締切：2026-09-25'
g = extract_gates(MAE)
check('前置き型 最早の関門', earliest_gate(g)[:2], ('参加申込', D(2026, 9, 10)))

# ── 4. 公告日・開催日を締切と誤認しない ──────────────────────
KOUKOKU = '''公告日 令和8年8月27日
開催期間 令和9年3月19日から令和9年9月26日まで
提案書の提出期限 令和8年10月15日（水）午後5時まで'''
g = extract_gates(KOUKOKU)
check('公告日を関門にしない', earliest_gate(g)[:2], ('提案書', D(2026, 10, 15)))
check('公告日は不明扱い', {d: k for k, d, t, s in g}.get(D(2026, 8, 27)), '不明')

# ── 5. 時刻の読み取り ─────────────────────────────────
for src, want in [('参加申込書の提出期限 令和8年9月1日 正午まで', T(12, 0)),
                  ('参加申込の締切 令和8年9月1日 午後5時まで', T(17, 0)),
                  ('参加申込の締切 令和8年9月1日 午前10時30分まで', T(10, 30)),
                  ('参加申込の締切 令和8年9月1日 16:00必着', T(16, 0)),
                  ('参加申込の締切 令和8年9月1日 17時必着', T(17, 0))]:
    check('時刻 %r' % src[-12:], extract_gates(src)[0][2], want)

# ── 6. **日付が読めても種別が読めないものを捨てない** ────────────
g = extract_gates('令和8年9月1日 なにか')
check('ラベル不明でも返す', [(k, d) for k, d, t, s in g], [('不明', D(2026, 9, 1))])

print('\n%d件成功 / %d件失敗' % (ok, fail))
sys.exit(1 if fail else 0)
